/**
 * オープンデータの「該当あり」を表す記号の判定。
 *
 * ## なぜ関数にするのか
 *
 * 丸印には**見た目がほぼ同じ別の文字**が2つある。
 *
 * | 文字 | コードポイント | 名前 |
 * | --- | --- | --- |
 * | 〇 | U+3007 | IDEOGRAPHIC NUMBER ZERO（漢数字のゼロ） |
 * | ○ | U+25CB | WHITE CIRCLE（幾何学記号の白丸） |
 *
 * 飲食店バリアフリー情報（No.8）の実データは **U+3007** だった。
 * U+25CB と比較していたため、外国語メニュー130件・ハラール54件・
 * ベジタリアン73件のフラグが黙って全部 false になっていた
 * （エラーにならず、note からその情報だけが消える形で壊れる）。
 *
 * 目視やエディタでは区別できないため、比較を1か所に集めてテストで固定する。
 */

/** 「〇」(U+3007) と「○」(U+25CB) のどちらでも該当ありとみなす */
export function isCircleYes(value: string | undefined): boolean {
  const v = (value ?? "").trim();
  return v === "〇" || v === "○";
}
